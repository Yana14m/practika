def start_scheduler() -> None:
    """
    ЗАПУСКАЕТ ФОНОВЫЙ ПЛАНИРОВЩИК ЗАДАЧ.
    
    ЧТО ДЕЛАЕТ:
    1. Создаёт объект BackgroundScheduler — он работает в фоновом потоке
    2. Добавляет задание: каждые CHECK_INTERVAL_MINUTES минут вызывать check_and_notify()
    3. Запускает планировщик
    
    КОГДА ВЫЗЫВАТЬ:
    При запуске бота (в main.py), чтобы уведомления начали работать автоматически.
    
    ПРИМЕЧАНИЕ:
    Scheduler работает в фоновом потоке и не блокирует основной поток (бот).
    Это значит, что бот может принимать сообщения от пользователей,
    пока планировщик занимается проверкой дедлайнов.
    """
    
    # Создаём планировщик с настройками по умолчанию
    # BackgroundScheduler — работает в отдельном потоке, не блокирует главный
    scheduler = BackgroundScheduler(
        timezone='Europe/Moscow'  # Указываем часовой пояс (Москва)
    )
    
    # Добавляем задачу в планировщик
    scheduler.add_job(
        check_and_notify,  # Функция, которую нужно вызывать
        trigger=IntervalTrigger(minutes=CHECK_INTERVAL_MINUTES),  # Как часто
        id='notify_job',  # Уникальный идентификатор задачи
        replace_existing=True  # Если задача с таким ID уже есть — заменяем
    )
    
    # Запускаем планировщик
    scheduler.start()
    
    # Логируем успешный запуск
    logger.info(f"?? ПЛАНИРОВЩИК УВЕДОМЛЕНИЙ ЗАПУЩЕН")
    logger.info(f"   Интервал проверки: {CHECK_INTERVAL_MINUTES} минут")
    logger.info(f"   Уведомление за: {NOTIFY_DAYS_BEFORE} день(дней) до дедлайна")
    logger.info(f"   Следующая проверка: через {CHECK_INTERVAL_MINUTES} минут")


