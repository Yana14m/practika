# но не слишком часто, чтобы не нагружать базу данных
CHECK_INTERVAL_MINUTES = 15

# ЗА СКОЛЬКО ДНЕЙ ДО ДЕДЛАЙНА ОТПРАВЛЯТЬ УВЕДОМЛЕНИЕ
# 1 день - стандартное напоминание. Можно настроить 2 или 3 дня при необходимости
NOTIFY_DAYS_BEFORE = 1


