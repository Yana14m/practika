# ОСНОВНАЯ ФУНКЦИЯ ПРОВЕРКИ И ОТПРАВКИ УВЕДОМЛЕНИЙ
# ============================================================================

def check_and_notify() -> None:
    """
    ОСНОВНАЯ ФУНКЦИЯ МОДУЛЯ УВЕДОМЛЕНИЙ.
    
    ЧТО ДЕЛАЕТ:
    1. Запрашивает из базы данных список заданий, у которых:
       - дедлайн наступает через 1 день (NOTIFY_DAYS_BEFORE)
       - статус = 'active' (задание ещё не сдано)
       - notified_1day = 0 (уведомление ещё не отправлялось)
       - пользователь активен (is_active = 1)
    
    2. Для каждого найденного задания:
       - Формирует понятное сообщение для пользователя
       - Отправляет сообщение через модуль бота
       - Отмечает в базе данных, что уведомление отправлено
    
    3. Всё логируется для отслеживания работы
    
    КОГДА ВЫЗЫВАЕТСЯ:
    Автоматически по расписанию (каждые CHECK_INTERVAL_MINUTES минут).
    Также может быть вызвана вручную для тестирования.
    """
    
    # Пишем в лог, что началась проверка (для отладки)
    logger.info("=" * 60)
    logger.info("ЗАПУСК ПРОВЕРКИ ДЕДЛАЙНОВ")
    logger.info("=" * 60)
    
    try:
        # ШАГ 1: ПОЛУЧАЕМ СПИСОК ЗАДАНИЙ ДЛЯ УВЕДОМЛЕНИЯ
        # ====================================================================
        # Вызываем функцию из database.py, которая возвращает список словарей.
        # Каждый словарь содержит:
        #   - telegram_id: ID пользователя (кому отправлять)
        #   - assignment_id: ID задания в базе (чтобы отметить отправку)
        #   - title: название задания
        #   - deadline: дата и время дедлайна
        #   - discipline_name: название дисциплины (предмета)
        notifications = get_users_for_notification(days=NOTIFY_DAYS_BEFORE)
        
        # Если список пустой — значит, нет заданий, требующих уведомления
        if not notifications:
            logger.info("? Нет заданий для уведомления. Проверка завершена.")
            return
        
        # Если список не пустой — выводим количество найденных заданий
        logger.info(f"?? Найдено {len(notifications)} заданий для уведомления.")
        logger.info("-" * 40)
        
        # ШАГ 2: ОТПРАВЛЯЕМ УВЕДОМЛЕНИЯ ДЛЯ КАЖДОГО ЗАДАНИЯ
        # ====================================================================
        # Переменная для подсчёта успешно отправленных уведомлений
        sent_count = 0
        
        for item in notifications:
            # Извлекаем данные из текущего словаря
            user_id = item['telegram_id']          # ID пользователя в MAX (строка)
            assignment_id = item['assignment_id']  # ID задания в базе данных (число)
            title = item['title']                  # Название задания
            deadline = item['deadline']            # Дата дедлайна
            discipline = item['discipline_name']   # Название предмета
            
            logger.info(f"?? Обработка задания: {discipline} - {title}")
            logger.info(f"   ?? Пользователь: {user_id}")
            logger.info(f"   ? Дедлайн: {deadline}")
            
            # ШАГ 2.1: ФОРМИРУЕМ ТЕКСТ УВЕДОМЛЕНИЯ
            # ====================================================================
            # Сообщение должно быть:
            # - Информативным: пользователь должен понять, о чём напоминание
            # - Дружелюбным: используем эмодзи и понятный язык
            # - Конкретным: указываем предмет, задание и дату дедлайна
            
            # Преобразуем дату в читаемый формат (для пользователя)
            # Исходный формат: "2026-07-20 23:59:00"
            # Преобразуем в: "20 июля 2026 г., 23:59"
            try:
                dt = datetime.strptime(deadline, '%Y-%m-%d %H:%M:%S')
                deadline_readable = dt.strftime('%d %B %Y г., %H:%M')
                # %d — день, %B — полное название месяца, %Y — год, %H:%M — часы:минуты
                # Русские названия месяцев не работают в стандартной библиотеке,
                # но для простоты оставим так. Можно доработать с locale.
            except:
                # Если не удалось преобразовать — оставляем как есть
                deadline_readable = deadline
            
            message = (
                f"?? НАПОМИНАНИЕ О ДЕДЛАЙНЕ!\n"
                f"\n"
                f"?? Предмет: {discipline}\n"
                f"?? Задание: {title}\n"
                f"? Дедлайн: {deadline_readable}\n"
                f"\n"
                f"? Остался 1 день — не забудьте сдать работу!\n"
                f"?? Удачи!"
            )
            
            logger.info(f"   ?? Сформировано сообщение:")
            logger.info(f"      {message.replace(chr(10), '; ')}")  # Вывод в одну строку для лога
            
            # ШАГ 2.2: ОТПРАВЛЯЕМ СООБЩЕНИЕ ПОЛЬЗОВАТЕЛЮ
            # ====================================================================
            try:
                # Вызываем функцию из модуля бота
                # Она отправляет сообщение через API MAX
                send_message_to_user(user_id, message)
                logger.info(f"   ? Уведомление успешно отправлено пользователю {user_id}")
                
                # ШАГ 2.3: ОТМЕЧАЕМ УВЕДОМЛЕНИЕ КАК ОТПРАВЛЕННОЕ
                # ====================================================================
                # Это важно, чтобы при следующей проверке не отправить дубликат
                if mark_notification_sent(assignment_id):
                    logger.info(f"   ? Отметка об отправке установлена (assignment_id={assignment_id})")
                    sent_count += 1  # Увеличиваем счётчик успешных отправок
                else:
                    # Если не удалось отметить — это проблема, но мы всё равно отправили
                    logger.error(f"   ? НЕ УДАЛОСЬ ОТМЕТИТЬ УВЕДОМЛЕНИЕ (assignment_id={assignment_id})")
                    
            except Exception as e:
                # Если произошла ошибка при отправке сообщения
                logger.error(f"   ? ОШИБКА ПРИ ОТПРАВКЕ пользователю {user_id}: {e}")
                # В этом случае уведомление НЕ отмечается как отправленное
                # При следующей проверке система попытается отправить его снова
                continue  # Переходим к следующему заданию в списке
        
        # ШАГ 3: ВЫВОДИМ ИТОГОВУЮ СТАТИСТИКУ
        # ====================================================================
        logger.info("-" * 40)
        logger.info(f"?? ИТОГИ ПРОВЕРКИ:")
        logger.info(f"   Всего заданий для уведомления: {len(notifications)}")
        logger.info(f"   Успешно отправлено: {sent_count}")
        logger.info(f"   С ошибками: {len(notifications) - sent_count}")
        logger.info("=" * 60)
        
    except Exception as e:
        # Если произошла критическая ошибка (например, проблемы с базой данных)
        logger.error(f"? КРИТИЧЕСКАЯ ОШИБКА В ПРОЦЕССЕ ПРОВЕРКИ: {e}")
        logger.error(f"   Подробности: {type(e).__name__}")
        # В реальном проекте можно добавить отправку уведомления администратору


